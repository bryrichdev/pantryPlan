-- Photos of a recipe's dish. Each upload is shrunk and re-encoded as a JPEG
-- before it is stored, so a photo is a few hundred kilobytes, and the camera's
-- metadata (GPS position included) is gone.
--
-- The picture bytes live in their own table. recipe_photos is audited like the
-- other recipe tables, and the audit trigger copies every column of a changed
-- row into the log, so keeping the bytes out of it keeps the log small.

CREATE TABLE recipe_photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT      NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    position   INT         NOT NULL,
    width      INT         NOT NULL,
    height     INT         NOT NULL,
    byte_size  INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_recipe_photos_position CHECK (position >= 0),
    CONSTRAINT ck_recipe_photos_size CHECK (width > 0 AND height > 0 AND byte_size > 0)
);

CREATE INDEX ix_recipe_photos_recipe ON recipe_photos (recipe_id, position);

CREATE TABLE recipe_photo_files (
    photo_id  BIGINT PRIMARY KEY REFERENCES recipe_photos (id) ON DELETE CASCADE,
    image     BYTEA NOT NULL,
    thumbnail BYTEA NOT NULL
);

-- JPEG is already compressed; skip Postgres's own compression attempt.
ALTER TABLE recipe_photo_files ALTER COLUMN image SET STORAGE EXTERNAL;
ALTER TABLE recipe_photo_files ALTER COLUMN thumbnail SET STORAGE EXTERNAL;

CREATE TRIGGER audit_recipe_photos AFTER INSERT OR UPDATE OR DELETE ON recipe_photos
    FOR EACH ROW EXECUTE FUNCTION audit_row_change();
