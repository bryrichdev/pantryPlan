-- Groups: cooks sharing recipes with friends and family.
--
-- A user creates at most one group and can belong to any number. Members hold
-- one of four roles, highest first: OWNER, ADMIN, MEMBER, VIEWER. Recipes are
-- shared into a group, not handed over. The recipe and its ingredients stay
-- in the sharer's account, and another member who wants to cook it copies it
-- into their own account, where it is matched to their own ingredients.
--
-- Names become unique per account regardless of case first, so a copy can
-- always be matched to an existing recipe or ingredient by name.

-- ------------------------------------------------- case-insensitive names

-- The app has always refused a duplicate name ignoring case, but only for
-- ingredients did the database back that up, and there only for exact case.
-- Any duplicates that slipped in keep the oldest row's name; the rest get
-- their id appended, which is unique, so the new indexes always build.

UPDATE recipes r
SET name = LEFT(r.name, 130) || ' (' || r.id || ')'
FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY user_id, LOWER(name) ORDER BY id) AS rn
      FROM recipes) d
WHERE r.id = d.id AND d.rn > 1;

UPDATE ingredients i
SET name = LEFT(i.name, 100) || ' (' || i.id || ')'
FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY user_id, LOWER(name) ORDER BY id) AS rn
      FROM ingredients) d
WHERE i.id = d.id AND d.rn > 1;

CREATE UNIQUE INDEX uq_recipes_user_name_ci ON recipes (user_id, LOWER(name));

ALTER TABLE ingredients DROP CONSTRAINT uq_ingredients_user_name;
CREATE UNIQUE INDEX uq_ingredients_user_name_ci ON ingredients (user_id, LOWER(name));

-- ------------------------------------------------------------------ groups

-- owner_id is what makes "one group per creator" a database rule, and what
-- removes the group with its owner's account. The owner also has an OWNER
-- membership row, so every permission check reads one table.
CREATE TABLE kitchen_groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_kitchen_groups_owner UNIQUE (owner_id),
    CONSTRAINT ck_kitchen_groups_name CHECK (LENGTH(TRIM(name)) > 0)
);

CREATE TABLE group_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id   BIGINT      NOT NULL REFERENCES kitchen_groups (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role       VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_group_members UNIQUE (group_id, user_id),
    CONSTRAINT ck_group_members_role CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER', 'VIEWER'))
);

-- Exactly one owner per group, and one owned group per user.
CREATE UNIQUE INDEX uq_group_members_one_owner_per_group ON group_members (group_id) WHERE role = 'OWNER';
CREATE UNIQUE INDEX uq_group_members_one_group_per_owner ON group_members (user_id) WHERE role = 'OWNER';
CREATE INDEX ix_group_members_user ON group_members (user_id);

-- --------------------------------------------------------------- invites

-- Only a SHA-256 digest of the link's token is stored. The token itself is
-- shown once, when the link is made, so a leaked database or audit log cannot
-- be turned back into working links. A link can join people as MEMBER or
-- VIEWER only; anything higher is granted by hand afterwards.
CREATE TABLE group_invite_links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT      NOT NULL REFERENCES kitchen_groups (id) ON DELETE CASCADE,
    created_by_id BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    token_hash    VARCHAR(64) NOT NULL,
    role          VARCHAR(10) NOT NULL,
    expires_at    TIMESTAMPTZ NOT NULL,
    max_uses      INTEGER,
    use_count     INTEGER     NOT NULL DEFAULT 0,
    revoked_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_group_invite_links_token UNIQUE (token_hash),
    CONSTRAINT ck_group_invite_links_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_group_invite_links_role CHECK (role IN ('MEMBER', 'VIEWER')),
    CONSTRAINT ck_group_invite_links_max_uses CHECK (max_uses IS NULL OR max_uses > 0),
    CONSTRAINT ck_group_invite_links_use_count
        CHECK (use_count >= 0 AND (max_uses IS NULL OR use_count <= max_uses))
);

CREATE INDEX ix_group_invite_links_group ON group_invite_links (group_id);

-- Invitations name an email, not an account. Whether that email belongs to
-- anyone is never revealed to the person inviting: the invitation is stored
-- and listed the same way either way, and shows up for whoever signs in with
-- that email before it expires.
CREATE TABLE group_invitations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT       NOT NULL REFERENCES kitchen_groups (id) ON DELETE CASCADE,
    invited_by_id BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    email         VARCHAR(255) NOT NULL,
    role          VARCHAR(10)  NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_group_invitations UNIQUE (group_id, email),
    CONSTRAINT ck_group_invitations_role CHECK (role IN ('MEMBER', 'VIEWER')),
    CONSTRAINT ck_group_invitations_email_lower CHECK (email = LOWER(email))
);

CREATE INDEX ix_group_invitations_email ON group_invitations (email);

-- --------------------------------------------------------- recipe shares

CREATE TABLE recipe_shares (
    recipe_id BIGINT      NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    group_id  BIGINT      NOT NULL REFERENCES kitchen_groups (id) ON DELETE CASCADE,
    shared_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (recipe_id, group_id)
);

CREATE INDEX ix_recipe_shares_group ON recipe_shares (group_id);

-- A recipe may only be shared into a group by an owner, admin, or member of
-- it. The service checks first and gives a message; this makes sure no other
-- path, such as a tampered form, can get around it.
CREATE FUNCTION recipe_share_requires_sharer() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM recipes r
        JOIN group_members m ON m.user_id = r.user_id
        WHERE r.id = NEW.recipe_id
          AND m.group_id = NEW.group_id
          AND m.role IN ('OWNER', 'ADMIN', 'MEMBER')
    ) THEN
        RAISE EXCEPTION 'the owner of recipe % may not share into group %', NEW.recipe_id, NEW.group_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER recipe_shares_require_sharer
    BEFORE INSERT OR UPDATE ON recipe_shares
    FOR EACH ROW EXECUTE FUNCTION recipe_share_requires_sharer();

-- When someone leaves, is removed, or is made a viewer, what they shared into
-- that group is withdrawn with them. Doing it here means it also happens when
-- the membership goes by cascade, for example with a deleted account.
CREATE FUNCTION withdraw_shares_of_former_sharer() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR NEW.role = 'VIEWER' THEN
        DELETE FROM recipe_shares s
        USING recipes r
        WHERE s.recipe_id = r.id
          AND s.group_id = OLD.group_id
          AND r.user_id = OLD.user_id;
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER group_members_withdraw_shares
    AFTER DELETE OR UPDATE OF role ON group_members
    FOR EACH ROW EXECUTE FUNCTION withdraw_shares_of_former_sharer();

